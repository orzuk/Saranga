#!/usr/bin/env python3
"""Choose which gold files git tracks: writes corpus/gold_candidates/.gitignore and corpus/gold_blueprints/.gitignore.

The root .gitignore ignores everything under both folders; these files re-include, per gold item, the files
that make up the gold set (as for the silver: the flattened source and the rule-based graph, plus the gold graph).

  author      the good diagrams of index.json: paper.tex (flattened source), gold.json (the gold graph),
              meta.json, figure.json, graph_tikz.json (the diagram as parsed), rules.json (rule-based graph,
              the one scored); also eval_subset.txt (the evaluation subset: reliable, >= 0.05 arrows per KB)
  blueprint   the scored blueprints (human or mixed, with proofs, not degenerate): all.tex, macros.tex,
              graph.json (the gold graph), meta.json, rules.json

Not tracked: PDFs, page images, HTML pages, original packages, full.json (the pages' copy of rules.json),
tagger.json, scores.json. Re-run after the index changes:

    track_gold.py
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import score_gold                                       # noqa: E402

AUTHOR = ("paper.tex", "gold.json", "meta.json", "figure.json", "graph_tikz.json", "rules.json")
BLUEPRINT = ("all.tex", "macros.tex", "graph.json", "meta.json", "rules.json")
TOP = {"author": ("index.json", "review_sample.json", "scores_summary.json", "eval_subset.txt"),
       "blueprint": ("index.json", "scores_summary.json", "paper_pairs_summary.json", "SOURCES_TO_CONVERT.md",
                     "excluded.json", "quality.json")}
ARROWS_PER_KB = 0.05


def eval_subset(root: Path) -> list:
    index = json.loads((root / "index.json").read_text())
    return [r["id"] for r in index if r["good"] and r["class"] == "results, reliable"
            and r["n_edges"] / ((root / "papers" / r["id"] / "paper.tex").stat().st_size / 1024) >= ARROWS_PER_KB]


def write(name: str, files: tuple) -> None:
    root = score_gold.SETS[name][0]
    lines = ["# Generated by scripts/gold_candidates/track_gold.py: the gold files git tracks. Do not edit.",
             *(f"!/{f}" for f in TOP[name])]
    n = 0
    for d in score_gold.items(name):
        rel = d.relative_to(root).as_posix()
        lines += [f"!/{rel}/{f}" for f in files if (d / f).is_file()]
        n += 1
    (root / ".gitignore").write_text("\n".join(lines) + "\n")
    print(f"{name}: {n} items, {len(lines) - 1 - len(TOP[name])} files")


def main():
    root = score_gold.SETS["author"][0]
    sub = eval_subset(root)
    (root / "eval_subset.txt").write_text(
        f"# Evaluation subset: good, 'results, reliable', >= {ARROWS_PER_KB} arrows per KB of LaTeX ({len(sub)} papers)\n"
        + "\n".join(sub) + "\n")
    write("author", AUTHOR)
    write("blueprint", BLUEPRINT)


if __name__ == "__main__":
    main()
