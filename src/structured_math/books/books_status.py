"""Progress of the v7-books foundation by topic: which books have source, which chapters are
extracted. Reads foundation_books.json and the books_v7b/{prepared,graphs} folders.

    python -m structured_math.books.books_status [ROOT]     (ROOT default: <DATASET_ROOT>/foundation/books_v7b)
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def book_state(b: dict, root: Path) -> tuple[str, int, int]:
    """(state, chapters extracted, chapters prepared)."""
    prep = root / "prepared" / b.get("prepared", "")
    n = len(b.get("chapters") or json.loads((prep / "chapters.json").read_text())["chapters"]) \
        if b.get("prepared") and (prep / "chapters.json").is_file() else 0          # "chapters": the ones worth extracting
    done = len(list((root / "graphs" / b["id"]).glob("ch[0-9][0-9].json")))
    if n and done >= n:
        return "done", done, n
    if done:
        return "extracting", done, n
    if n:
        return "prepared", done, n
    return ("source" if b["source"] == "have" else b["source"].split(":")[0]), done, n


def write_md(cat: dict, states: dict, root: Path) -> None:
    """root/BOOKS.md: every topic with its books, their format, licence, status and where they are."""
    src = HERE.parents[2] / "textbooks/source"
    rows = ["# Foundation books (v7-books)", "",
            "Generated by `python -m structured_math.books.books_status --md`. Format: latex/pretext "
            "(extracted from source), pdf (needs PDF -> LaTeX first; files in pdf/), none (links to try).", ""]
    for t in cat["topics"]:
        bs = [b for b in cat["books"] if t in b["topics"]]
        rows += [f"## {t}", ""]
        if not bs:
            rows += ["Nothing found yet.", ""]
            continue
        rows += ["| book | format | licence | status | where / links |", "|---|---|---|---|---|"]
        for b in bs:
            s, d, n = states[b["id"]]
            fmt = b.get("format") or ("pdf" if b.get("pdf") else "latex/pretext" if b.get("src") else "?")
            where = (f"`{src / b['src']}`" if b.get("src") else f"`{b['pdf']}`" if b.get("pdf") else "")
            links = " ".join(b.get("urls", []))
            note = b["source"].split(": ", 1)[1] if ":" in b["source"] else ""
            rows.append(f"| {b['title']} | {fmt} | {b.get('license', '')} | {s}" + (f" {d}/{n}" if n else "")
                        + f" | {where} {links} {note} |")
        rows.append("")
    (root / "BOOKS.md").write_text("\n".join(rows))
    print("wrote", root / "BOOKS.md")


def main():
    sys.path.insert(0, str(HERE.parents[1]))
    from config import DATASET_ROOT
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = Path(args[0]) if args else Path(DATASET_ROOT) / "foundation/books_v7b"
    cat = json.loads((HERE / "foundation_books.json").read_text())
    rank = {"done": 0, "extracting": 1, "prepared": 2, "source": 3, "pdf": 4, "pending": 5, "none": 6, "blocked": 7}
    states = {b["id"]: book_state(b, root) for b in cat["books"]}
    if "--md" in sys.argv:
        write_md(cat, states, root)
        return
    print(f"{'topic':32} {'status':11} books")
    for t in cat["topics"]:
        bs = sorted((b for b in cat["books"] if t in b["topics"]), key=lambda b: rank[states[b["id"]][0]])
        best = states[bs[0]["id"]][0] if bs else "nothing"
        shown = "; ".join(f"{b['id']} {s}" + (f" {d}/{n}" if n else "")
                          for b in bs for s, d, n in [states[b["id"]]])
        print(f"{t:32} {best:11} {shown or '-'}")


if __name__ == "__main__":
    main()
